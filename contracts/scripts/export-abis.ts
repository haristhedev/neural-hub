/** Writes web/src/lib/web3/abis.generated.ts from Hardhat artifacts (typed `as const` ABIs). */
import fs from "node:fs";
import path from "node:path";

const names = ["NHUSD", "ModelNFT", "ModelLicenses", "Marketplace"] as const;
const out = path.resolve(__dirname, "../../web/src/lib/web3/abis.generated.ts");

let src = "/* eslint-disable */\n// AUTO-GENERATED by contracts/scripts/export-abis.ts — do not edit.\n\n";
for (const n of names) {
  const artifact = JSON.parse(fs.readFileSync(path.resolve(__dirname, `../artifacts/contracts/${n}.sol/${n}.json`), "utf8"));
  const camel = n[0].toLowerCase() + n.slice(1);
  src += `export const ${camel}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
console.log("Wrote", out);
